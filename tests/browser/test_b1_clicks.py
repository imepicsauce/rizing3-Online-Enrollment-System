"""Browser suite 1: real clicks through login, admin lists, delete buttons, student pages, print view, change password."""
from helpers import *
import os
try:
    from playwright.sync_api import sync_playwright
except ImportError:
    sys.exit("Browser tests need Playwright:  pip install playwright   then   playwright install chromium")
SHOTS = os.path.join(REPO, "tests", "screenshots")
os.makedirs(SHOTS, exist_ok=True)

with sync_playwright() as pw:
    b = pw.chromium.launch()
    ctx = b.new_context(viewport={"width": 1280, "height": 900}); page = ctx.new_page()
    dialogs = []
    def on_dialog(d): dialogs.append((d.type, d.message)); d.accept()
    page.on("dialog", on_dialog)
    errors = []; page.on("pageerror", lambda e: errors.append(str(e)))
    def last(): return dialogs[-1][1] if dialogs else None
    def where(): return page.url.replace(BASE, "/")

    section("wrong password")
    page.goto(BASE + "index.php"); page.fill("input[name=username]", "admins"); page.fill("input[name=password]", "nope"); page.click("input[name=submit]"); page.wait_for_timeout(400)
    check("alert text is exactly: User doesn't exist please try again.", last() == "User doesn't exist please try again.", last())
    check("stays on the login page", where().endswith("index.php"), where())

    section("admin session (real clicks)")
    page.fill("input[name=username]", "admins"); page.fill("input[name=password]", "admins"); page.click("input[name=submit]"); page.wait_for_url("**/Admin/adminindex.php")
    check("login alert said 'Successfully log in as Administrator' and landed on the admin home", last() == "Successfully log in as Administrator" and where() == "/Admin/adminindex.php", (last(), where()))
    page.click("a.nav-link:has-text('Manage Subjects')"); page.wait_for_url("**/subjectreg.php")
    page.click("img[src*='iconadd2']"); page.wait_for_url("**/addnewsubj.php")
    page.screenshot(path=SHOTS + "/b1_admin_addsubj.png", full_page=True)
    page.fill("input[name=scode]", "BR101"); page.fill("input[name=stitle]", "Browser Test Subject"); page.select_option("select[name=numunits]", "4")
    page.fill("input[name=sroom]", "R9"); page.fill("input[name=sday]", "MWF"); page.fill("input[name=stime]", "9-10"); page.fill("input[name=sinstructor]", "Mr Z")
    page.click("input[name=register]"); page.wait_for_timeout(600)
    check("adding a subject through the form shows the success alert", last() == "Successfully Created new Subject", last())
    check("subject is in the database", sql("select count(*) from subjecttbl where subjectcode='BR101'") == "1")
    page.click("a.nav-link:has-text('Manage Subjects')"); page.wait_for_url("**/subjectreg.php"); page.wait_for_timeout(300)
    page.screenshot(path=SHOTS + "/b1_admin_subjects.png", full_page=True)
    row = page.locator("tr", has_text="BR101"); check("new subject appears in the list", row.count() == 1)
    row.locator("button.link-button").click(); page.wait_for_timeout(700)
    check("DELETE asks for confirmation, then removes the subject", [d[1] for d in dialogs[-2:]] == ["Are you sure?", "Successfully Removed the selected subject"] and sql("select count(*) from subjecttbl where subjectcode='BR101'") == "0", dialogs[-2:])
    check("...and returns to the subject list", where().endswith("subjectreg.php"), where())

    page.click("a.nav-link:has-text('Manage Users')"); page.wait_for_url("**/userreg.php"); page.wait_for_timeout(300)
    page.screenshot(path=SHOTS + "/b1_admin_users.png", full_page=True)
    sql("insert into usertbl (username,password,fullname,user_type) values ('victim','pw','Victim Student','student')")
    sql("insert into studenttbl (accountID,studnum,fname,minitial,lname,course,yearlvl) select ID,'V-1','Victim','V','Student','bsit','I-1' from usertbl where username='victim'")
    page.reload(); page.wait_for_timeout(300)
    r = page.locator("tr", has_text="V-1"); check("student row shows Year Level then Course", r.count() == 1 and "I-1" in r.inner_text() and r.inner_text().index("I-1") < r.inner_text().index("bsit"), r.inner_text() if r.count() else "no row")
    r.locator("button.link-button").click(); page.wait_for_timeout(700)
    check("deleting a user: confirm + success alert, account gone", [d[1] for d in dialogs[-2:]] == ["Are you sure? This also deletes the student's profile and enrollment forms.", "Successfully Removed the selected account"] and sql("select count(*) from usertbl where username='victim'") == "0", dialogs[-2:])
    page.click("img[title='edit admin details']"); page.wait_for_url("**/adminedit.php"); page.screenshot(path=SHOTS + "/b1_admin_edit.png", full_page=True)
    page.click("a.nav-link:has-text('Generate Report')"); page.wait_for_url("**/Admin/report.php")
    check("Generate Report opens the enrollment report", "ENROLLMENT REPORT" in page.inner_text("body"))
    page.go_back(); page.click("a.nav-link:has-text('Log Out')"); page.wait_for_url("**/index.php")
    check("Log Out returns to the login page", where() == "/index.php", where())
    page.goto(BASE + "Admin/userreg.php"); page.wait_for_timeout(300)
    check("after logout, typing the admin URL sends you back to login", where() == "/index.php", where())

    section("student session (real clicks)")
    page.fill("input[name=username]", "dennis"); page.fill("input[name=password]", "123456"); page.click("input[name=submit]"); page.wait_for_url("**/student/studentindex.php")
    check("student login alert + lands on student home", last() == "Successfully log in as Student", last())
    page.click("a.nav-link:has-text('Curriculum')"); page.wait_for_url("**/curriculum.php"); page.screenshot(path=SHOTS + "/b1_student_curriculum.png", full_page=True)
    check("Curriculum button shows the BSIT subject list", all(x in page.inner_text("body") for x in ["IT201", "IT202", "Total units"]))
    page.click("a.nav-link:has-text('Profile')"); page.wait_for_url("**/studentprofile.php"); page.screenshot(path=SHOTS + "/b1_student_profile.png", full_page=True)
    check("profile footer sits OUTSIDE the form (HTML balanced)", page.evaluate("document.querySelector('form') && !document.querySelector('form').contains(document.querySelector('#footer'))"))
    page.emulate_media(media="print")
    hidden = page.evaluate("['.header','nav.container','#footer','.no-print'].every(s => getComputedStyle(document.querySelector(s)).display === 'none')")
    check("print view hides banner, menus, footer and the buttons", hidden); page.screenshot(path=SHOTS + "/b1_student_profile_print.png", full_page=True); page.emulate_media(media="screen")
    page.click("input[value='My Enrollment Report']"); page.wait_for_url("**/student/report.php"); check("My Enrollment Report button works", "MY ENROLLMENT REPORT" in page.inner_text("body"))
    page.go_back(); page.click("input[value='Change Password']"); page.wait_for_url("**/changepass.php")
    page.fill("input[name=opassword]", "123456"); page.fill("input[name=password]", "aaa"); page.fill("input[name=password2]", "bbb"); page.click("input[name=cpass]"); page.wait_for_timeout(400)
    check("mismatched passwords now show a message", last() == "The new passwords do not match. Please try again.", last())
    page.fill("input[name=opassword]", "123456"); page.fill("input[name=password]", "zzz999"); page.fill("input[name=password2]", "zzz999"); page.click("input[name=cpass]"); page.wait_for_url("**/studentprofile.php")
    check("successful change alerts and returns to the profile", last() == "Successfully updated the password" and where().endswith("studentprofile.php"), (last(), where()))
    check("password changed in the database", sql("select password from usertbl where username='dennis'") .startswith("$2y$"))
    sql("update usertbl set password='123456' where username='dennis'")
    page.click("input[value='Back to Home']"); page.wait_for_url("**/studentindex.php")
    page.goto(BASE + "Admin/adminindex.php"); page.wait_for_timeout(400)
    check("a student typing an Admin URL is sent back to login", where() == "/index.php", where())
    check("no JavaScript errors were thrown on any page", not errors, errors)
    b.close()
finish()
